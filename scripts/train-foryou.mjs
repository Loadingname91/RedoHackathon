// Synthetic data + training for the "For you" ranking. No network, no database.
// usage: node scripts/train-foryou.mjs   -> writes src/data/affinity.json and checks the model learned the hidden tastes.
// shortcut: trained on made-up students; once real feedback (feedback table + participants.interests) exists, train on that instead.
import fs from 'node:fs'
import assert from 'node:assert'
import { INTERESTS } from '../src/lib/foryou.js'
import { OFFERS, rng, pick, rate, truth, makeStudents } from './synthetic.mjs'

const STUDENTS = 300, EVENTS_EACH = 10
const rand = rng(42)

// 1) Generate: each student rates 10 past events with 1–3 offerings.
const rows = []
for (const s of makeStudents(rand, STUDENTS)) {
  for (let k = 0; k < EVENTS_EACH; k++) {
    const offers = pick(rand, OFFERS, 1 + Math.floor(rand() * 3))
    rows.push({ interests: s.interests, offers, rating: rate(rand, s.interests, offers) })
  }
}

// 2) Train: linear regression on interest×offering pairs, gradient descent with L2. 80/20 train/test split.
const split = Math.floor(rows.length * 0.8), train = rows.slice(0, split), test = rows.slice(split)
const mean = train.reduce((s, r) => s + r.rating, 0) / train.length
const W = Object.fromEntries(INTERESTS.map((i) => [i, Object.fromEntries(OFFERS.map((o) => [o, 0]))]))
const predict = (r) => { let y = mean; for (const i of r.interests) for (const o of r.offers) y += W[i][o]; return y }
for (let epoch = 0; epoch < 60; epoch++) {
  for (const r of train) {
    const err = predict(r) - r.rating
    for (const i of r.interests) for (const o of r.offers) W[i][o] -= 0.02 * (err + 0.01 * W[i][o])
  }
}

// 3) Check: the model beats "everyone gets the average" on unseen ratings, and its weights match the hidden tastes.
const mae = (f) => test.reduce((s, r) => s + Math.abs(Math.min(3, Math.max(1, f(r))) - r.rating), 0) / test.length
const modelMAE = mae(predict), baselineMAE = mae(() => mean)
const a = [], b = []
for (const i of INTERESTS) for (const o of OFFERS) { a.push(W[i][o]); b.push(truth(i, o)) }
const avg = (v) => v.reduce((s, x) => s + x, 0) / v.length
const ma = avg(a), mb = avg(b)
const corr = a.reduce((s, x, k) => s + (x - ma) * (b[k] - mb), 0) / Math.sqrt(a.reduce((s, x) => s + (x - ma) ** 2, 0) * b.reduce((s, x) => s + (x - mb) ** 2, 0))
console.log(`${rows.length} synthetic ratings from ${STUDENTS} students`)
console.log(`test error: model ${modelMAE.toFixed(2)} vs average-guess ${baselineMAE.toFixed(2)} (lower is better)`)
console.log(`learned weights vs hidden tastes: correlation ${corr.toFixed(2)}`)
for (const i of INTERESTS) {
  const top = Object.entries(W[i]).sort((x, y) => y[1] - x[1])[0]
  console.log(`  ${i.padEnd(7)} likes most: ${top[0]} (${top[1].toFixed(2)})`)
}
assert.ok(modelMAE < baselineMAE * 0.85, 'model should clearly beat the average guess')
assert.ok(corr > 0.8, 'model should recover the hidden tastes')

const round = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, Math.round(v * 100) / 100]))
fs.writeFileSync(new URL('../src/data/affinity.json', import.meta.url), JSON.stringify({
  note: 'Generated by scripts/train-foryou.mjs from synthetic students. Weight = how much an interest raises the rating of an offering.',
  ratings: rows.length, test_error: +modelMAE.toFixed(3), baseline_error: +baselineMAE.toFixed(3), correlation_with_truth: +corr.toFixed(3),
  weights: Object.fromEntries(INTERESTS.map((i) => [i, round(W[i])])),
}, null, 2) + '\n')
console.log('wrote src/data/affinity.json')
